export function getLocalAssessment(id: string): StaticAssessment | null {
  const resolved = COURSE_TO_ASSESSMENT_MAP[id] || id
  if (ASSESSMENTS_DATA[resolved]) return ASSESSMENTS_DATA[resolved]
  if (ASSESSMENTS_DATA[id]) return ASSESSMENTS_DATA[id]

  // Search by skill_id
  for (const item of Object.values(ASSESSMENTS_DATA)) {
    if (item.skill_id === id || item.id === `assessment-${id}`) {
      return item
    }
  }
  return null
}
